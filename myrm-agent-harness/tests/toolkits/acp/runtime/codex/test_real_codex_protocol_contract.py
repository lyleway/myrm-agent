def _obj(value: object) -> Mapping[str, object]:
    return value if isinstance(value, dict) else {}


def _items(value: object) -> list[object]:
    return value if isinstance(value, list) else []


def _tag(variant: Mapping[str, object]) -> str:
    """The value of a union variant's ``type`` (or ``method``) discriminator."""
    properties = _obj(variant.get("properties"))
    tag = _obj(properties.get("type") or properties.get("method")).get("enum")
    return str(_items(tag)[0])


def _strings(node: Mapping[str, object]) -> set[str]:
    """Every string an enum node allows, directly or through a union of enums."""
    nodes = [node, *(_obj(n) for n in [*_items(node.get("oneOf")), *_items(node.get("anyOf"))])]
    return {value for n in nodes for value in _items(n.get("enum")) if isinstance(value, str)}


@dataclass(frozen=True, slots=True)
class Schema:
    """The schema Codex generates: one bundle of its types, and one file for each message of the server's own."""

    directory: Path
    types: Mapping[str, Mapping[str, object]]

    def get(self, name: str) -> Mapping[str, object]:
        node = self.types.get(name)
        if node is None:
            path = self.directory / f"{name}.json"
            if not path.exists():
                pytest.fail(f"the installed Codex defines no type {name}")
            node = _obj(json.loads(path.read_text()))
        return node

    def fields(self, name: str) -> set[str]:
        return set(_obj(self.get(name).get("properties")))

    def variants(self, name: str) -> dict[str, set[str]]:
        """The fields of each variant of a union, by the variant's discriminator."""
        return {_tag(v): set(_obj(v.get("properties"))) for v in map(_obj, _items(self.get(name).get("oneOf")))}

    def methods(self, name: str) -> set[str]:
        return set(self.variants(name))

    def enum(self, name: str) -> set[str]:
        return _strings(self.get(name))


@pytest.fixture(scope="module")
def schema(tmp_path_factory: pytest.TempPathFactory) -> Schema:
    root = tmp_path_factory.mktemp("codex-schema")
    home = root / "home"
    home.mkdir()
    out = root / "schema"
    subprocess.run(
        [cli_binary("codex"), "app-server", "generate-json-schema", "--out", str(out)],
        check=True,
        env=probe_env(home),
        capture_output=True,
        timeout=_GENERATE_SECONDS,
    )
    return Schema(out, _obj(json.loads((out / _BUNDLE).read_text()).get("definitions")))  # type: ignore[arg-type]


def _unknown(used: Iterable[str], offered: set[str]) -> list[str]:
    return sorted(set(used) - offered)


def test_the_requests_the_host_makes_exist(schema: Schema) -> None:
    assert _unknown(_CLIENT_REQUESTS, schema.methods("ClientRequest")) == []
    assert _unknown(["initialized"], schema.methods("ClientNotification")) == []


def test_the_requests_the_host_answers_exist(schema: Schema) -> None:
    assert _unknown(_SERVER_REQUESTS, schema.methods("ServerRequest")) == []


def test_the_notifications_the_host_reads_or_opts_out_of_exist(schema: Schema) -> None:
    offered = schema.methods("ServerNotification")

    assert _unknown(READ_NOTIFICATIONS, offered) == []
    assert _unknown(OPT_OUT_NOTIFICATIONS, offered) == []


def test_the_handshake_and_login_use_fields_the_server_knows(schema: Schema) -> None:
    handshake = initialize_params()

    assert _unknown(handshake, schema.fields("InitializeParams")) == []
    assert _unknown(_obj(handshake["capabilities"]), schema.fields("InitializeCapabilities")) == []
    assert _unknown(config_read_params("/w"), schema.fields("ConfigReadParams")) == []
    assert _unknown(login_params("k"), schema.variants("LoginAccountParams")["apiKey"] | {"type"}) == []


def test_the_thread_and_turn_requests_use_fields_the_server_knows(schema: Schema) -> None:
    policy = turn_policy("safe", can_ask=True, workspace_write=WorkspaceWriteSettings())
    servers = [McpServerConfig(name="echo", command="python", args=["-V"], env={"A": "b"})]
    start = thread_params("/w", policy, mcp_servers=servers, ephemeral=True)
    resume = resume_params("t", "/w", policy, mcp_servers=servers)

    assert _unknown(start, schema.fields("ThreadStartParams")) == []
    assert _unknown(resume, schema.fields("ThreadResumeParams")) == []
    assert _unknown(turn_params("t", "hi", [], policy), schema.fields("TurnStartParams")) == []
    assert _unknown(["threadId", "turnId"], schema.fields("TurnInterruptParams")) == []


def test_the_prompt_is_text_and_images_are_local_files(schema: Schema) -> None:
    policy = turn_policy("safe", can_ask=True, workspace_write=WorkspaceWriteSettings())
    offered = schema.variants("UserInput")

    for item in map(_obj, _items(turn_params("t", "hi", ["/a.png"], policy)["input"])):
        assert _unknown(item, offered[str(item["type"])]) == []


def test_the_policies_the_host_picks_are_values_the_server_accepts(schema: Schema) -> None:
    approvals = schema.enum("AskForApproval")
    sandboxes = schema.enum("SandboxMode")
    policies = schema.variants("SandboxPolicy")
    settings = WorkspaceWriteSettings(("/x",), True, True, True)

    for mode in ("safe", "allow_all"):
        for can_ask in (True, False):
            chosen = turn_policy(mode, can_ask=can_ask, workspace_write=settings)
            assert chosen.approval in approvals
            assert chosen.sandbox in sandboxes
            assert _unknown(chosen.sandbox_policy, policies[str(chosen.sandbox_policy["type"])]) == []


def test_the_fields_the_host_reads_exist(schema: Schema) -> None:
    gone = {name: _unknown(fields, schema.fields(name)) for name, fields in _READ_FIELDS.items()}

    assert {name: fields for name, fields in gone.items() if fields} == {}


def test_the_fields_the_host_reads_of_each_kind_of_item_exist(schema: Schema) -> None:
    offered = schema.variants("ThreadItem")

    assert _unknown(_ITEM_FIELDS, set(offered)) == []
    gone = {kind: _unknown(fields, offered[kind]) for kind, fields in _ITEM_FIELDS.items()}
    assert {kind: fields for kind, fields in gone.items() if fields} == {}


def test_the_kinds_of_a_patch_change_the_host_tells_apart_exist(schema: Schema) -> None:
    kinds = schema.variants("PatchChangeKind")

    assert _unknown(["add", "delete", "update"], set(kinds)) == []
    assert "move_path" in kinds["update"]


def test_the_categories_of_a_failure_the_host_tells_apart_exist(schema: Schema) -> None:
    info = schema.get("CodexErrorInfo")
    with_status = {key for variant in _items(info.get("anyOf")) for key in _obj(_obj(variant).get("properties"))}

    assert _unknown(_CATEGORIES, schema.enum("CodexErrorInfo")) == []
    assert "responseStreamDisconnected" in with_status


def test_the_statuses_of_a_turn_exist(schema: Schema) -> None:
    assert _unknown(["completed", "interrupted", "failed"], schema.enum("TurnStatus")) == []


def test_the_answers_the_host_gives_are_values_the_server_accepts(schema: Schema) -> None:
    for file_name, decision in (
        ("CommandExecutionRequestApprovalResponse", "CommandExecutionApprovalDecision"),
        ("FileChangeRequestApprovalResponse", "FileChangeApprovalDecision"),
    ):
        decisions = _obj(_obj(schema.get(file_name).get("definitions")).get(decision))
        assert _unknown(["accept", "decline", "cancel"], _strings(decisions)) == []
    gone = {name: _unknown(fields, schema.fields(name)) for name, fields in _ANSWER_FIELDS.items()}
    assert {name: fields for name, fields in gone.items() if fields} == {}
