"""The app-server protocol the host speaks, held to the schema of the installed ``codex``.

The host writes this protocol by hand (``protocol.py``, ``turn_events.py``, ``approvals.py``, ``failure.py``), and
Codex moves it every release. A method or field that is renamed there does not raise here: a request is refused with a
generic error, or a ``.get`` finds nothing and a prompt silently never reaches a person. These tests generate the
schema of the binary under test (``codex app-server generate-json-schema``) and hold every method, parameter, field and
value the host uses against it, so the run against the latest Codex turns red where a release drifts.
"""

